"""Generate native help from the canonical command catalog (no runtime Python).

Run with --check in CI; ordinary application builds consume the checked-in file.
"""
from __future__ import annotations
import argparse
import json
from pathlib import Path
import textwrap

ROOT = Path(__file__).resolve().parents[1]


def render(catalog: dict) -> str:
    lines = [
        "Usage: wtop [--tui | --snapshot | --gui] [options]",
        "       wtop query processes|system|services [options]",
        "       wtop inspect PID [--command-line] [--services] [options]",
        "       wtop log --output PATH|- --samples COUNT|--duration MS [options]",
        "Long options accept --option=value. A final -- ends options.",
        "Inherited -d means snapshot; -n means name filter in every keymap.",
        "",
    ]
    for command in catalog["commands"]:
        if command["status"] == "planned":
            continue
        tokens = [token for token in command["tokens"] if token != "<default>"]
        lines.append("  " + ", ".join(tokens))
        if command["arguments"] != "none":
            lines.extend(textwrap.wrap(command["arguments"], 76, initial_indent="    ", subsequent_indent="    "))
        lines.extend(textwrap.wrap(command["behavior"], 76, initial_indent="    ", subsequent_indent="    "))
    lines += [
        "",
        "Process view: F1 Help, F2 Setup, F3 Search, F4 Filter, F5 Tree, F6 Sort,",
        "F7/F8 Windows priority class, F9 termination review, F10 Quit.",
        "Only y confirms termination; repeating F9 or Enter never confirms.",
        "Setup Tabs: F3 New, F4 Copy, F5 Rename, F6 Delete, F7/F8 Move, F9 Save.",
        "Function buttons change with context; keyboard and mouse share actions.",
        "B toggles the function bar; live status remains available.",
        "htop k opens Kill; vi j/k navigate. Emacs C-x C-s saves explicitly.",
        "Settings startup/exit never writes. :exec is explicit external launch.",
        "Text-grid display uses conservative ASCII cells; raw UTF-8 is preserved",
        "in JSON/settings, and encoding substitutions are reported.",
        "Exit: 0 completed, 1 runtime/output failure, 2 invalid/unavailable usage,",
        "3 incomplete requested query/provider/log work, 130 cancellation,",
        "124 emergency monitor shutdown. Native blocking calls have no universal",
        "deadline. Historical probes do not establish historical OS support.",
    ]
    output = [
        "/* Generated by tools/command_help.py from spec/catalog/commands.json. */",
        "static const char HelpText[] =",
        '    "Wtop " WTOP_VERSION_STRING " - NTop-derived Windows terminal monitor\\n"',
    ]
    output.extend("    " + json.dumps(line + "\n", ensure_ascii=True) for line in lines)
    output[-1] += ";"
    return "\n".join(output) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    destination = ROOT / "source/command_help.inc"
    expected = render(json.loads((ROOT / "spec/catalog/commands.json").read_text(encoding="utf-8")))
    if args.check:
        if not destination.exists() or destination.read_text(encoding="utf-8") != expected:
            parser.exit(1, "command help is stale; run python tools/command_help.py\n")
    else:
        destination.write_text(expected, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
